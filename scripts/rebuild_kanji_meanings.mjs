function isNoisyClause(text) {
  return NOISE_CLAUSE_PATTERNS.some((rx) => rx.test(text));
}

function cleanSingleGloss(raw) {
  let s = String(raw || '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!s) return '';

  // Loại bỏ ghi chú tham chiếu Hán tự hoặc phiên âm kiểu cũ trong ngoặc đơn
  s = s
    .replace(/\([^)]*[\u4e00-\u9faf][^)]*\)/g, '')
    .replace(/\(âm [^)]+\)/gi, '')
    .replace(/\(trong [^)]+\)/gi, '')
    .replace(/\(bằng [^)]+\)/gi, '')
    .replace(/\(đơn vị [^)]+\)/gi, '')
    .replace(/\s+/g, ' ')
    .replace(/^[,;\s]+|[,;\s]+$/g, '')
    .trim();

  if (!s || isNoisyClause(s)) return '';
  return s;
}

function sanitizeMeaningsList(list) {
  if (!Array.isArray(list)) return [];
  const seen = new Set();
  const out = [];

  for (const item of list) {
    // Tách theo dấu chấm phẩy nếu có, vẫn giữ nguyên ý trong một cụm phẩy hợp lý
    const subParts = String(item || '')
      .split(';')
      .map((p) => cleanSingleGloss(p))
      .filter(Boolean);

    for (const part of subParts) {
      const key = part.toLowerCase();
      if (!seen.has(key)) {
        seen.add(key);
        out.push(part);
      }
    }
  }
  return out;
}

function run() {
  const joyo = JSON.parse(fs.readFileSync(JOYO_PATH, 'utf8'));
  const viMap = JSON.parse(fs.readFileSync(VI_MAP_PATH, 'utf8'));

  let overriddenCount = 0;
  let sanitizedCount = 0;
  const emptyJoyo = [];

  for (const entry of joyo) {
    if (JOYO_VI_OVERRIDES[entry.c]) {
      entry.vi = [...JOYO_VI_OVERRIDES[entry.c]];
      overriddenCount++;
    } else {
      const before = JSON.stringify(entry.vi);
      entry.vi = sanitizeMeaningsList(entry.vi);
      if (JSON.stringify(entry.vi) !== before) sanitizedCount++;
    }

    if (!entry.vi || entry.vi.length === 0) {
      emptyJoyo.push(entry.c);
    }
  }

  if (emptyJoyo.length > 0) {
    console.error('❌ Phát hiện Jōyō Kanji rỗng nghĩa sau chuẩn hóa:', emptyJoyo);
    process.exit(1);
  }

  // Đồng bộ toàn bộ 2.136 Jōyō Kanji sang kanji_meanings_vi.json
  const joyoSet = new Set();
  let addedToViMap = 0;
  for (const entry of joyo) {
    joyoSet.add(entry.c);
    if (!viMap[entry.c]) addedToViMap++;
    viMap[entry.c] = [...entry.vi];
  }

  // Làm sạch phần ngoài Jōyō trong kanji_meanings_vi.json
  let nonJoyoCleaned = 0;
  let nonJoyoEmptied = 0;
  for (const [char, meanings] of Object.entries(viMap)) {
    if (joyoSet.has(char)) continue;
    const cleaned = sanitizeMeaningsList(meanings);
    if (JSON.stringify(cleaned) !== JSON.stringify(meanings)) {
      nonJoyoCleaned++;
      if (cleaned.length === 0) {
        delete viMap[char];
        nonJoyoEmptied++;
      } else {
        viMap[char] = cleaned;
      }
    }
  }

  // Kiểm định cuối cùng cho toàn bộ 2.136 Jōyō Kanji
  const auditIssues = [];
  for (const entry of joyo) {
    const joined = entry.vi.join(' | ');
    if (isNoisyClause(joined)) {
      auditIssues.push({ c: entry.c, lv: entry.lv, vi: entry.vi });
    }
    if (JSON.stringify(viMap[entry.c]) !== JSON.stringify(entry.vi)) {
      auditIssues.push({ c: entry.c, lv: entry.lv, error: 'Mismatch with viMap' });
    }
  }

  if (auditIssues.length > 0) {
    console.error('❌ Audit phát hiện lỗi còn sót:', JSON.stringify(auditIssues, null, 2));
    process.exit(1);
  }

  fs.writeFileSync(JOYO_PATH, JSON.stringify(joyo), 'utf8');
  fs.writeFileSync(VI_MAP_PATH, JSON.stringify(viMap), 'utf8');

  console.log('✅ Chuẩn hóa hoàn tất:');
  console.log(`   - Tổng Jōyō Kanji: ${joyo.length}`);
  console.log(`   - Ghi đè chuẩn Nhật-Việt: ${overriddenCount}`);
  console.log(`   - Lọc sạch tự động (Jōyō): ${sanitizedCount}`);
  console.log(`   - Bổ sung vào kho nghĩa mở rộng: ${addedToViMap}`);
  console.log(`   - Làm sạch mục ngoài Jōyō: ${nonJoyoCleaned} (trống để fallback API: ${nonJoyoEmptied})`);
  console.log(`   - Kiểm định lỗi còn sót: ${auditIssues.length}`);
}

run();
